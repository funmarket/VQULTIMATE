import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const sql = readFileSync(
  new URL('../supabase/migrations/20261106160000_trail_media_gallery.sql', import.meta.url),
  'utf8'
);
const gallerySource = readFileSync(
  new URL('../src/domains/d07_trails/gallery.ts', import.meta.url),
  'utf8'
);

test('migration reconciles trail_media to BIGINT identity without rewriting existing table', () => {
  assert.match(sql, /create table if not exists public\.trail_media/);
  assert.match(sql, /id bigint generated by default as identity primary key/);
  assert.doesNotMatch(sql, /id uuid primary key default gen_random_uuid\(\)/);
  assert.doesNotMatch(sql, /drop table /i);
});

test('migration validates legacy records and fails safely without fabricating data', () => {
  assert.match(sql, /Legacy trail_media records lack verifiable ownership or path data/);
  assert.match(sql, /where owner_auth_user_id is null/);
  assert.match(sql, /or trail_id is null/);
  assert.match(sql, /or object_path is null/);
});

test('policies and triggers are idempotent and can be safely reapplied', () => {
  assert.match(sql, /drop policy if exists trail_media_public_read on public\.trail_media;/);
  assert.match(sql, /drop policy if exists trail_media_owner_insert on public\.trail_media;/);
  assert.match(sql, /drop policy if exists trail_media_owner_update on public\.trail_media;/);
  assert.match(sql, /drop policy if exists trail_media_owner_delete on public\.trail_media;/);
  assert.match(sql, /drop trigger if exists vq_trail_media_guard_trigger on public\.trail_media;/);
  assert.match(sql, /drop trigger if exists vq_trail_media_legacy_cover_guard_trigger on public\.vibe_trails;/);
  assert.match(sql, /drop policy if exists vq_trail_attached_media_read on storage\.objects;/);
  assert.match(sql, /drop policy if exists vq_trail_unattached_media_owner_delete on storage\.objects;/);
});

test('column-level permissions protect sensitive fields without broad grants', () => {
  assert.match(sql, /revoke all on table public\.trail_media from anon, authenticated;/);
  assert.match(sql, /grant select\(id, trail_id, object_path, sort_order, is_cover, created_at\)/);
  assert.match(sql, /grant insert\(trail_id, object_path, sort_order, is_cover\)/);
  assert.match(sql, /grant update\(sort_order, is_cover\)/);
  assert.match(sql, /grant delete on public\.trail_media to authenticated;/);
});

test('media guard enforces path isolation, approved image types, and 5MB size limit', () => {
  assert.match(sql, /v_uid::text \|\| '\/trails\/' \|\| new\.trail_id \|\| '\/'/);
  assert.match(sql, /'image\/jpeg', 'image\/png', 'image\/webp'/);
  assert.match(sql, /v_size > 5242880/);
  assert.match(sql, /Trail photo limit reached/);
});

test('application gallery domain supports both BIGINT identity and string IDs cleanly', () => {
  assert.match(gallerySource, /id: string \| number;/);
  assert.match(gallerySource, /id: String\(row\.id\)/);
  assert.match(gallerySource, /createSignedUrl\(path, SIGNED_URL_SECONDS\)/);
});
